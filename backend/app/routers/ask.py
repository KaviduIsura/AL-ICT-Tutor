from typing import Optional
from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.security import AuthenticatedUser, get_current_user, security_scheme
from app.db.session import get_db
from app.schemas.ask import AskRequest
from app.services.ask_service import ask_service

router = APIRouter(tags=["Ask & Discuss"])


async def get_optional_current_user(
    token_auth=Depends(security_scheme),
) -> Optional[AuthenticatedUser]:
    """Allow optional authentication for guest exploration of Ask mode."""
    if not token_auth:
        return None
    try:
        from app.core.security import get_current_user
        return await get_current_user(token_auth)
    except Exception:
        return None


@router.post("/ask", summary="Ask the AI Tutor a question with grounded SSE token streaming")
async def ask_tutor_endpoint(
    request: AskRequest,
    current_user: Optional[AuthenticatedUser] = Depends(get_optional_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Grounded question answering endpoint (Section 8.2 & 10.2).
    
    Streams Server-Sent Events (SSE) including:
      - 'event: metadata' containing source citations, interaction ID, and confidence
      - 'event: token' containing answer tokens as generated by the LLM
      - 'event: done' indicating stream completion
    """
    generator = ask_service.execute_ask_stream(
        request=request,
        current_user=current_user,
        db=db,
    )

    return StreamingResponse(
        generator,
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )
